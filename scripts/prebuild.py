# PlatformIO pre-script: builds the panel (ui/) and generates src/generated/{version.h,ui.h}.
# Firmware and panel share one version: 0.001.YYYYMMDDHHMM.
import gzip
import os
import subprocess
import sys
from datetime import datetime

Import("env")  # noqa: F821 (provided by PlatformIO)

root = env.subst("$PROJECT_DIR")  # noqa: F821
ui_dir = os.path.join(root, "ui")
out_dir = os.path.join(root, "src", "generated")
version = os.environ.get("WHISLI_SENSE_VERSION") or "0.001." + datetime.now().strftime("%Y%m%d%H%M")


def write_if_changed(path, text):
    # Unchanged headers keep their timestamps, so nothing recompiles needlessly.
    if os.path.exists(path) and open(path, encoding="utf-8").read() == text:
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def build_ui():
    if not os.path.isdir(os.path.join(ui_dir, "node_modules")):
        sys.exit("ui/node_modules is missing - run: cd ui && npm install")
    npm = "npm.cmd" if os.name == "nt" else "npm"
    subprocess.run([npm, "run", "build"], cwd=ui_dir, check=True,
                   env={**os.environ, "WHISLI_SENSE_VERSION": version})
    html = open(os.path.join(ui_dir, "dist", "index.html"), "rb").read()
    data = gzip.compress(html, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    write_if_changed(os.path.join(out_dir, "ui.h"),
                     "// Generated by scripts/prebuild.py - do not edit.\n#pragma once\n#include <Arduino.h>\n\n"
                     f"static const uint8_t UI_GZ[] = {{\n  " + ",\n  ".join(rows) + "\n};\n")
    print(f"panel: {len(html)} B -> {len(data)} B gzip")


os.makedirs(out_dir, exist_ok=True)
write_if_changed(os.path.join(out_dir, "version.h"),
                 f'// Generated by scripts/prebuild.py - do not edit.\n#pragma once\n#define FIRMWARE_VERSION "{version}"\n')
# Only real builds need the panel; IDE indexing and `pio run -t clean` do not.
# WHISLI_SENSE_SKIP_UI=1 keeps the last built panel (faster firmware-only builds).
skip = os.environ.get("WHISLI_SENSE_SKIP_UI") == "1" and os.path.exists(os.path.join(out_dir, "ui.h"))
if not skip and not env.GetOption("clean") and "idedata" not in COMMAND_LINE_TARGETS:  # noqa: F821
    build_ui()
